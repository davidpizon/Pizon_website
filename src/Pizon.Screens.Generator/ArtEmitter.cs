using System.Globalization;
using System.Text;

namespace Pizon.Screens.Generator;

/// <summary>
/// Writes the C# class for one piece of compiled art.
/// </summary>
internal static class ArtEmitter
{
    /// <summary>The namespace of the generated classes.</summary>
    public const string Namespace = "Pizon.Web.Client.Screens.Art";

    private const string Rendering = "global::Pizon.Web.Client.Screens.Rendering";

    /// <summary>
    /// Turns an art file name into a class name: <c>main-menu.dur</c> becomes <c>MainMenuArt</c>.
    /// </summary>
    /// <param name="fileName">The file name without folders.</param>
    /// <returns>The class name.</returns>
    public static string ClassName(string fileName)
    {
        var stem = Path.GetFileNameWithoutExtension(fileName);
        var sb = new StringBuilder();
        var upper = true;
        foreach (var c in stem)
        {
            if (c is (>= 'a' and <= 'z') or (>= 'A' and <= 'Z') or (>= '0' and <= '9'))
            {
                sb.Append(upper ? char.ToUpperInvariant(c) : c);
                upper = false;
            }
            else
            {
                upper = true;
            }
        }

        if (sb.Length == 0 || char.IsDigit(sb[0]))
        {
            sb.Insert(0, "Art");
        }

        return sb.Append("Art").ToString();
    }

    /// <summary>
    /// Writes the class.
    /// </summary>
    /// <param name="fileName">The art's file name (for the docs and the art's name).</param>
    /// <param name="grid">The art, with placeholders already blanked.</param>
    /// <param name="scan">The slots and hotspots.</param>
    /// <returns>The C# source.</returns>
    public static string Emit(string fileName, ArtGrid grid, ScanResult scan)
    {
        var className = ClassName(fileName);
        var stem = Path.GetFileNameWithoutExtension(fileName);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Compiled by Pizon.Screens.Generator from " + fileName + ". Edit the art, not this file.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.Append("namespace ").Append(Namespace).AppendLine(";");
        sb.AppendLine();
        sb.Append("/// <summary>The compiled art from <c>").Append(Xml(fileName)).Append("</c> (")
            .Append(Invariant(grid.Columns)).Append(" x ").Append(Invariant(grid.Rows)).AppendLine(" cells).</summary>");
        sb.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Pizon.Screens.Generator\", \"1.0.0\")]");
        sb.Append("internal sealed class ").Append(className).Append(" : ").Append(Rendering).AppendLine(".ScreenArt");
        sb.AppendLine("{");
        sb.AppendLine("    private const string CellText =");
        for (var row = 0; row < grid.Rows; row++)
        {
            sb.Append("        ").Append(Literal(new string(grid.Chars, row * grid.Columns, grid.Columns)))
                .AppendLine(row == grid.Rows - 1 ? ";" : " +");
        }

        sb.AppendLine();
        sb.Append("    private static readonly byte[] ForegroundColors = ").Append(Bytes(grid.Foreground)).AppendLine(";");
        sb.AppendLine();
        sb.Append("    private static readonly byte[] BackgroundColors = ").Append(Bytes(grid.Background)).AppendLine(";");
        sb.AppendLine();
        sb.Append("    private ").Append(className).AppendLine("()");
        sb.Append("        : base(").Append(Literal(stem)).Append(", ").Append(Invariant(grid.Columns)).Append(", ")
            .Append(Invariant(grid.Rows)).AppendLine(", CellText, ForegroundColors, BackgroundColors,");
        sb.Append("            [").Append(string.Join(", ", scan.Slots.Select(s => SlotProperty(s)))).AppendLine("],");
        sb.Append("            [").Append(string.Join(", ", scan.Hotspots.Select(Hotspot))).AppendLine("])");
        sb.AppendLine("    {");
        sb.AppendLine("    }");
        foreach (var slot in scan.Slots)
        {
            sb.AppendLine();
            sb.Append("    /// <summary>Gets the <c>").Append(Xml(Token(slot))).Append("</c> ").Append(slot.Kind.ToLowerInvariant())
                .Append(" (row ").Append(Invariant(slot.Row)).Append(", column ").Append(Invariant(slot.Column)).Append(", ")
                .Append(Invariant(slot.Width)).Append(" x ").Append(Invariant(slot.Height)).AppendLine(").</summary>");
            sb.Append("    public static ").Append(Rendering).Append(".FieldSlot ").Append(SlotProperty(slot)).Append(" { get; } = new(")
                .Append(Literal(slot.Name)).Append(", ").Append(Rendering).Append(".SlotKind.").Append(slot.Kind).Append(", ")
                .Append(Invariant(slot.Row)).Append(", ").Append(Invariant(slot.Column)).Append(", ")
                .Append(Invariant(slot.Width)).Append(", ").Append(Invariant(slot.Height)).Append(", ")
                .Append(Invariant(slot.Foreground)).Append(", ").Append(Invariant(slot.Background)).Append(", ")
                .Append("global::Pizon.Doors.Sdk.Text.TextAlign.").Append(slot.Align).AppendLine(");");
        }

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Gets the one instance of this art. It is declared last so the slots above exist first.</summary>");
        sb.Append("    public static ").Append(className).AppendLine(" Instance { get; } = new();");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string SlotProperty(ArtSlot slot) => SlotScanner.PropertyName(slot.Name);

    private static string Token(ArtSlot slot) => "@" + (slot.Kind == "Input" ? "?" : slot.Kind == "Animation" ? "ANIM:" : string.Empty) + slot.Name + "@";

    private static string Hotspot(ArtHotspot h) =>
        "new " + Rendering + ".HotspotSlot(" + Literal(h.Key) + ", " + Invariant(h.Row) + ", " + Invariant(h.Column) + ", " + Invariant(h.Width) + ")";

    private static string Bytes(byte[] values)
    {
        var sb = new StringBuilder("[");
        for (var i = 0; i < values.Length; i++)
        {
            if (i > 0)
            {
                sb.Append(',');
            }

            sb.Append(Invariant(values[i]));
        }

        return sb.Append(']').ToString();
    }

    /// <summary>
    /// Writes a C# string literal, escaping quotes, backslashes and anything outside printable ASCII.
    /// </summary>
    /// <param name="value">The string.</param>
    /// <returns>The literal, with quotes.</returns>
    internal static string Literal(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (var c in value)
        {
            if (c is '"' or '\\')
            {
                sb.Append('\\').Append(c);
            }
            else if (c is >= ' ' and <= '~')
            {
                sb.Append(c);
            }
            else
            {
                sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
            }
        }

        return sb.Append('"').ToString();
    }

    private static string Invariant(int value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Xml(string value) => value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
